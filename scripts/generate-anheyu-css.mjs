import fs from "node:fs";
import path from "node:path";
import { loadTheme, root } from "../src/lib/load-site.mjs";

const theme = loadTheme();

function getByPath(obj, p) {
  return String(p)
    .split(".")
    .reduce((o, k) => (o == null ? o : o[k]), obj);
}

const tplPath = path.join(root, "src/styles/one-graph-flow.css");
if (!fs.existsSync(tplPath)) {
  console.error(`missing template: ${tplPath}`);
  process.exit(1);
}

let css = fs.readFileSync(tplPath, "utf8");
const missing = [];
css = css.replace(/\{\{([a-zA-Z0-9_.]+)\}\}/g, (_, key) => {
  const val = getByPath(theme, key);
  if (val == null || val === "") {
    missing.push(key);
    return `/* missing ${key} */`;
  }
  return String(val);
});

if (missing.length) {
  console.error(`missing theme.yml keys:\n  - ${missing.join("\n  - ")}`);
  process.exit(1);
}

const out = path.join(root, "public/css/one-graph-flow.css");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `/* generated by scripts/generate-anheyu-css.mjs — edit src/config/theme.yml and src/styles/one-graph-flow.css */\n${css}`,
);
console.log(`generated css (${(css.length / 1024).toFixed(1)} KB) -> public/css/one-graph-flow.css`);
